import { defineConfig } from 'orval';

// The internal clients of the gateway, one per called service, generated from the spec that the
// installed @cadenway/contracts ships (`specs/openapi/internal/<service>.yaml`), never from a sibling
// checkout. `pnpm generate:clients` writes them into src/clients/generated/; they are committed,
// never edited by hand, and CI fails when they differ from what the installed contracts generate.
//
// The fetch client is generated as a factory (`httpClientInjection: 'factory'`): it takes its fetch
// implementation once, and src/clients/ hands it the `fetch` of an InternalHttpClient of
// @cadenway/nest-common, which adds the deadline, the retry, the circuit breaker and the internal
// token. The generated paths are relative (`/internal/v1/...`): the InternalHttpClient resolves them
// against `<NAME>_SERVICE_URL` and refuses any other origin.
export default defineConfig({
  'identity-service': {
    input: {
      target: './node_modules/@cadenway/contracts/specs/openapi/internal/identity-service.yaml',
    },
    output: {
      client: 'fetch',
      mode: 'single',
      target: './src/clients/generated/identity-service.ts',
      override: {
        header: (): string[] => [
          'Generated by orval from @cadenway/contracts/specs/openapi/internal/identity-service.yaml.',
          'Do not edit: run `pnpm generate:clients`.',
        ],
        fetch: {
          httpClientInjection: 'factory',
          includeHttpResponseReturnType: true,
        },
      },
    },
  },
  'organization-service': {
    input: {
      target: './node_modules/@cadenway/contracts/specs/openapi/internal/organization-service.yaml',
    },
    output: {
      client: 'fetch',
      mode: 'single',
      target: './src/clients/generated/organization-service.ts',
      override: {
        header: (): string[] => [
          'Generated by orval from @cadenway/contracts/specs/openapi/internal/organization-service.yaml.',
          'Do not edit: run `pnpm generate:clients`.',
        ],
        fetch: {
          httpClientInjection: 'factory',
          includeHttpResponseReturnType: true,
        },
      },
    },
  },
});
